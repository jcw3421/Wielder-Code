namespace Game.Core
{
    /// 카메라 흔들림의 세기 등급. "얼마나 흔들지"의 실제 수치는 카메라 쪽이 들고 있고,
    /// 발행자(보스 패턴 등)는 등급만 고른다 — 연출 튜닝을 카메라 한 곳에 모으기 위해서다.
    public enum CameraShakeStrength
    {
        /// 흔들지 않는다.
        None = 0,

        /// 약한 패턴 — 짧고 얕게. 가벼운 타격, 연계 중간 조각.
        Light = 1,

        /// 큰 패턴 — 길고 깊게. 한 방이 무겁거나 화면 전체를 덮는 패턴.
        Heavy = 2,
    }
}
